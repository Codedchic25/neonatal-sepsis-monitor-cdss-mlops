def test_guardrail_accepts_valid_clinical_report() -> None:
    """Verifies that a fully compliant XML payload passes guardrail validation successfully."""
    guardrail = NeonatalOutputGuardrail()
    valid_payload = (
        "<RAPORT>\nPatient is stable. No signs of advanced systemic shock.\n</RAPORT>\n"
        "<MEDICATIE>\nAdminister Ampicillin 250 mg IV on q12h schedule.\n</MEDICATIE>\n"
        "<FCC>\nKangaroo care active for 60 minutes inside the stable incubator environment.\n</FCC>"
    )

    # Fixed: Unpacking the new tuple return format (success, cleaned_output)
    success, cleaned_output = guardrail.validate_structure(valid_payload)
    assert success is True
    assert "<RAPORT>" in cleaned_output
    assert guardrail.validate_clinical_safety(valid_payload, weight_kg=2.50) is True


def test_guardrail_self_heals_missing_fcc_tag() -> None:
    """Verifies that the guardrail successfully injects the fallback FCC block if omitted by the LLM."""
    guardrail = NeonatalOutputGuardrail()
    incomplete_payload = (
        "<RAPORT>\nPatient is recovering nicely under monitoring.\n</RAPORT>\n"
        "<MEDICATIE>\nAdminister basic fluids 20 ml.\n</MEDICATIE>"
    )

    success, cleaned_output = guardrail.validate_structure(incomplete_payload)
    assert success is True
    assert "<FCC>" in cleaned_output.upper()  # Confirms self-healing injected the block
    assert "Family-Centered Care" in cleaned_output


def test_guardrail_raises_exception_on_broken_xml_structure() -> None:
    """Verifies that an unclosed or missing structural partition tag triggers a strict structure exception."""
    guardrail = NeonatalOutputGuardrail()
    corrupt_payload = (
        "<RAPORT>\nPatient data is visible.\n</RAPORT>\n"
        "<MEDICATIE>\nAdminister Ampicillin 250 mg IV.\n"  # Missing </MEDICATIE> closing tag
        "<FCC>\nSoundstage mitigation active.\n</FCC>"
    )

    with pytest.raises(ClinicalGuardrailException, match="Critical structure failure"):
        guardrail.validate_structure(corrupt_payload)


def test_guardrail_intercepts_absolute_ceiling_dosage_breach() -> None:
    """Guarantees the guardrail blocks dosages exceeding the absolute maximum neonatal threshold (>500mg)."""
    guardrail = NeonatalOutputGuardrail()
    dangerous_payload = (
        "<RAPORT>\nHigh risk patient diagnostics active.\n</RAPORT>\n"
        "<MEDICATIE>\nAdminister generic compound 750 mg immediately via IV drip.\n</MEDICATIE>\n"
        "<FCC>\nMaintain low ambient noise.\n</FCC>"
    )

    with pytest.raises(
        ClinicalGuardrailException, match="exceeds absolute neonatal ceiling"
    ):
        guardrail.validate_clinical_safety(dangerous_payload, weight_kg=2.50)


def test_guardrail_intercepts_weight_relative_dosage_breach() -> None:
    """Guarantees the guardrail intercepts a high dosage relative to an extremely low neonatal weight."""
    guardrail = NeonatalOutputGuardrail()
    # 200 mg is below the 500mg absolute ceiling, but for a 1.0 kg premature baby,
    # it represents 200 mg/kg, which violates our smart 150 mg/kg threshold.
    dangerous_payload = (
        "<RAPORT>\nPremature infant shows early systemic distress markers.\n</RAPORT>\n"
        "<MEDICATIE>\nAdminister high dose aggressive baseline 200mg IV loop.\n</MEDICATIE>\n"
        "<FCC>\nMinimize infant handling cycles.\n</FCC>"
    )

    with pytest.raises(ClinicalGuardrailException, match="critically high"):
        guardrail.validate_clinical_safety(dangerous_payload, weight_kg=1.00)
