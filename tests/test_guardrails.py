"""Unit tests for the post-inference semantic XML extraction and parsing layer.

Validates that structural formatting, token boundaries, and language tags are
isolated correctly from remote inference wrappers or fallback payloads.
"""

import pytest

from src.guardrails.guardrails import (
    ClinicalGuardrailException,
    NeonatalOutputGuardrail,
)


def extract_tag_flexible_mock(text: str, tag_name: str) -> str:
    """Mock implementation mirroring app.py's exact internal parsing logic.

    Ensures regular expression substitutions and character casing configurations
    are tested in structural isolation.
    """
    tag_lower = tag_name.lower()
    start_tag = f"<{tag_lower}>"
    end_tag = f"</{tag_lower}>"

    # Normalize uppercase/lowercase XML tags generated by the LLM wrapper
    text_norm = text.replace(f"<{tag_name.upper()}>", start_tag).replace(
        f"</{tag_name.upper()}>", end_tag
    )

    if start_tag in text_norm:
        parts = text_norm.split(start_tag)
        if len(parts) > 1:
            content_part = parts[1]
            if end_tag in content_part:
                return content_part.split(end_tag)[0].strip()
            return content_part.strip()
    return ""


def test_parser_extracts_correct_casing() -> None:
    """Verifies that lowercase XML boundary enclosures are isolated cleanly."""
    llm_payload = (
        "<raport>The neonate shows stable telemetry parameters.</raport>"
        "<medicatie>Maintain standard baseline intervals.</medicatie>"
    )

    extracted_raport = extract_tag_flexible_mock(llm_payload, "RAPORT")
    extracted_med = extract_tag_flexible_mock(llm_payload, "MEDICATIE")

    assert extracted_raport == "The neonate shows stable telemetry parameters."
    assert extracted_med == "Maintain standard baseline intervals."


def test_parser_extracts_uppercase_casing() -> None:
    """Verifies that uppercase XML tags are normalized and parsed without truncation."""
    llm_payload = (
        "<RAPORT>Analiza clinica arata parametri fiziologici stabili.</RAPORT>"
        "<FCC>Protocoale FCC active in incubator.</FCC>"
    )

    extracted_raport = extract_tag_flexible_mock(llm_payload, "raport")
    extracted_fcc = extract_tag_flexible_mock(llm_payload, "fcc")

    assert extracted_raport == "Analiza clinica arata parametri fiziologici stabili."
    assert extracted_fcc == "Protocoale FCC active in incubator."


def test_parser_returns_empty_on_missing_boundaries() -> None:
    """Guarantees that raw unstructured strings return an empty fallback to prevent crashes."""
    unstructured_payload = (
        "The model failed to encapsulate this content within XML tokens."
    )

    extracted_raport = extract_tag_flexible_mock(unstructured_payload, "RAPORT")
    assert extracted_raport == ""


